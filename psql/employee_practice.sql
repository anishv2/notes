DROP TABLE IF EXISTS employee_projects, projects, salaries, employees, departments CASCADE;

CREATE TABLE departments (
    department_id SERIAL PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(100) NOT NULL
);

CREATE TABLE employees (
    employee_id SERIAL PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    phone VARCHAR(20),
    job_title VARCHAR(100) NOT NULL,
    department_id INT REFERENCES departments(department_id),
    manager_id INT REFERENCES employees(employee_id),
    hire_date DATE NOT NULL,
    birth_date DATE,
    employment_status VARCHAR(20) NOT NULL CHECK (employment_status IN ('Active','On Leave','Resigned')),
    city VARCHAR(100)
);

CREATE TABLE salaries (
    salary_id SERIAL PRIMARY KEY,
    employee_id INT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    salary NUMERIC(12,2) NOT NULL CHECK (salary > 0),
    effective_from DATE NOT NULL,
    effective_to DATE
);

CREATE TABLE projects (
    project_id SERIAL PRIMARY KEY,
    project_name VARCHAR(150) NOT NULL,
    department_id INT REFERENCES departments(department_id),
    budget NUMERIC(14,2),
    start_date DATE NOT NULL,
    end_date DATE
);

CREATE TABLE employee_projects (
    employee_id INT REFERENCES employees(employee_id) ON DELETE CASCADE,
    project_id INT REFERENCES projects(project_id) ON DELETE CASCADE,
    assigned_date DATE NOT NULL,
    hours_per_week INT CHECK (hours_per_week BETWEEN 1 AND 40),
    PRIMARY KEY (employee_id, project_id)
);

